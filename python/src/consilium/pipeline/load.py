"""Stage 9: copy parquet into Postgres, then build vector and text indexes.

Rows are loaded in foreign-key order with ``COPY`` into a temporary staging
table and an upsert into the target. ``patch`` and ``report_chunk`` identities
are generated by Postgres: existing rows for the incoming slides and reports
are deleted first, then the new rows are copied. ``slide``, ``path_case``,
``report``, ``patient``, ``pathologist``, and ``concept`` are updated in place
so a reload does not ``ON DELETE CASCADE`` through ``slide`` into ``annotation``.

App-written tables (``annotation``, ``consult_thread``, ``consult_message``,
``ingestion_job``) are left alone unless ``--replace-fixtures`` is set, and
then only rows that belong to fixture cases are removed.

``0001_init.sql`` is applied first, without requiring ``0002_indexes.sql``.
Index build runs afterwards, including when those indexes already exist.
``migrate`` still refuses Lakebase URLs (SKO-280). The ``COPY`` statements
are ordinary parameterised psycopg SQL and do not depend on that refusal.
"""

