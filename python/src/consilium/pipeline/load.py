def _load_slides_pending(conn: psycopg.Connection, path: Path) -> None:
    """Insert slides as ``pending`` so the ready-asset check can wait for patches.

    ``embedding`` and ``thumb_pack_key`` stay null until every patch for the
    slide is in. Updating in place keeps ``annotation`` rows on that slide.
    """
    columns = (
        "id",
        "case_id",
        "ordinal",
        "stain",
        "magnification",
        "mpp",
        "width",
        "height",
        "patch_size",
        "patch_count",
        "storage_key",
        "thumb_pack_key",
        "source_path",
        "embedding",
        "status",
        "created_at",
    )
    rows = [
        (
            _text(row["id"]),
            _text(row["case_id"]),
            _required_int(row.get("ordinal"), "slide ordinal"),
            _text(row["stain"]),
            float(row["magnification"]),
            float(row["mpp"]),
            _required_int(row.get("width"), "slide width"),
            _required_int(row.get("height"), "slide height"),
            _required_int(row.get("patch_size"), "slide patch_size"),
            _required_int(row.get("patch_count"), "slide patch_count"),
            _text(row["storage_key"]),
            _optional_text(row.get("thumb_pack_key")),
            _text(row["source_path"]),
            _vector_text(row.get("embedding")),
            _text(row["status"]),
            _timestamp(row.get("created_at")),
        )
        for row in _read_rows(path)
    ]
    _stage(conn, "slide", columns, rows, vector_columns=("embedding",))
    skipped = {"embedding", "thumb_pack_key", "status"}
    pending = tuple(column for column in columns if column not in skipped)
    select_list = sql.SQL(", ").join(
        [
            *(sql.Identifier(column) for column in pending),
            sql.SQL("null::halfvec(768)"),
            sql.SQL("null::text"),
            sql.SQL("'pending'"),
        ]
    )
    column_list = sql.SQL(", ").join(
        sql.Identifier(column) for column in (*pending, "embedding", "thumb_pack_key", "status")
    )
    assignments = sql.SQL(", ").join(
        sql.SQL("{} = excluded.{}").format(sql.Identifier(column), sql.Identifier(column))
        for column in pending
    )
    conn.execute(
        sql.SQL(
            """
            insert into slide ({columns})
            select {select_list}
            from staging_slide
            on conflict (id) do update set
                {assignments},
                embedding = null,
                thumb_pack_key = null,
                status = 'pending'
            """
        ).format(columns=column_list, select_list=select_list, assignments=assignments)
    )


