def _mark_slides_ready(conn: psycopg.Connection) -> None:
    conn.execute(
        """
        update slide as target
        set status = 'ready',
            embedding = incoming.embedding::halfvec(768),
            thumb_pack_key = incoming.thumb_pack_key,
            patch_count = incoming.patch_count,
            case_id = incoming.case_id,
            ordinal = incoming.ordinal,
            stain = incoming.stain,
            magnification = incoming.magnification,
            mpp = incoming.mpp,
            width = incoming.width,
            height = incoming.height,
            patch_size = incoming.patch_size,
            storage_key = incoming.storage_key,
            source_path = incoming.source_path
        from staging_slide as incoming
        where target.id = incoming.id
          and incoming.status = 'ready'
          and incoming.embedding is not null
          and incoming.thumb_pack_key is not null
        """
    )
    stranded = conn.execute(
        """
        select incoming.id
        from staging_slide as incoming
        join slide as target on target.id = incoming.id
        where incoming.status = 'ready'
          and target.status <> 'ready'
        """
    ).fetchall()
    if stranded:
        ids = ", ".join(row[0] for row in stranded[:5])
        raise RuntimeError(f"slides stayed pending after their patches loaded: {ids}")


def _replace_fixtures(conn: psycopg.Connection, directory: Path) -> None:
    """Remove seeded fixture rows before the real parquet is loaded.

    Fixture cases are ``source_dataset = 'fixture'``, source ids beginning
    with ``FX-``, or the ids from ``seed_data`` when that module is
    installed (SKO-259). Cases that are not fixtures stay, including their
    annotations, consult threads, and ingestion jobs. Dependent rows of a
    fixture case are removed with it. Pathologists and concepts that the
    incoming parquet still names are left for the upsert.
    """
    seed_cases, seed_patients, seed_pathologists, seed_concepts = _seed_ids()
    case_rows = conn.execute(
        """
        select id, patient_id
        from path_case
        where source_dataset = 'fixture'
           or source_case_id like 'FX-%%'
           or id like '%%-FX-%%'
           or id = any(%s)
        """,
        (list(seed_cases),),
    ).fetchall()
    case_ids = [row[0] for row in case_rows]
    patient_ids = {row[1] for row in case_rows} | seed_patients
    if case_ids:
        slide_ids = [
            row[0]
            for row in conn.execute(
                "select id from slide where case_id = any(%s)",
                (case_ids,),
            ).fetchall()
        ]
        conn.execute(
            """
            delete from consult_message
            where thread_id in (select id from consult_thread where case_id = any(%s))
            """,
            (case_ids,),
        )
        conn.execute("delete from consult_thread where case_id = any(%s)", (case_ids,))
        conn.execute(
            "delete from annotation where case_id = any(%s) or slide_id = any(%s)",
            (case_ids, slide_ids),
        )
        conn.execute(
            "delete from patch where case_id = any(%s) or slide_id = any(%s)",
            (case_ids, slide_ids),
        )
        conn.execute(
            """
            delete from report_chunk
            where case_id = any(%s)
               or report_id in (select id from report where case_id = any(%s))
            """,
            (case_ids, case_ids),
        )
        conn.execute(
            "delete from ingestion_job where case_id = any(%s) or slide_id = any(%s)",
            (case_ids, slide_ids),
        )
        conn.execute("delete from report where case_id = any(%s)", (case_ids,))
        conn.execute("delete from slide where case_id = any(%s)", (case_ids,))
        conn.execute("delete from path_case where id = any(%s)", (case_ids,))
    if patient_ids:
        conn.execute(
            """
            delete from patient
            where id = any(%s)
              and not exists (select 1 from path_case where path_case.patient_id = patient.id)
            """,
            (list(patient_ids),),
        )
    incoming_concepts = _column_values(directory / PARQUET_FILES["concept"], "id")
    incoming_pathologists = _column_values(directory / PARQUET_FILES["pathologist"], "id")
    if seed_concepts:
        conn.execute(
            "delete from concept where id = any(%s) and id <> all(%s)",
            (list(seed_concepts), incoming_concepts or [""]),
        )
    if seed_pathologists:
        conn.execute(
            """
            delete from pathologist as person
            where person.id = any(%s)
              and person.id <> all(%s)
              and not exists (
                  select 1 from path_case where path_case.assigned_to = person.id
              )
              and not exists (select 1 from report where report.author_id = person.id)
              and not exists (
                  select 1 from annotation where annotation.author_id = person.id
              )
              and not exists (
                  select 1 from consult_thread where consult_thread.user_id = person.id
              )
              and not exists (
                  select 1 from ingestion_job where ingestion_job.requested_by = person.id
              )
            """,
            (list(seed_pathologists), incoming_pathologists or [""]),
        )


def _seed_ids() -> tuple[set[str], set[str], set[str], set[str]]:
    try:
        from consilium.seed_data import (  # pragma: allowlist secret
            CASES,
            CONCEPTS,
            PATIENTS,
            ROSTER,
        )
    except ImportError:
        return set(), set(), set(), set()
    return (
        {case.id for case in CASES},
        {patient.id for patient in PATIENTS},
        {person.id for person in ROSTER},
        {concept.id for concept in CONCEPTS},
    )


def _ensure_indexes(conn: psycopg.Connection) -> tuple[list[str], dict[str, str]]:
    """Build pending HNSW and GIN indexes, then ``ANALYZE``.

    Session settings are best-effort. Managed Postgres may reject them; the
    index statements still run with the server defaults. Files already recorded
    in ``schema_migration`` are not executed again.
    """
    conn.autocommit = True
    maintenance = _set_maintenance(conn)
    pending = _pending_indexes(conn)
    applied: list[str] = []
    with conn.transaction():
        for item in pending:
            script = item.path.read_text(encoding="utf-8")
            for statement in split_sql(script):
                conn.execute(statement)
            conn.execute(
                "insert into schema_migration (filename, checksum) values (%s, %s)",
                (item.filename, item.checksum),
            )
            applied.append(item.filename)
        conn.execute(_ANALYZE)
    return applied, maintenance


def _set_maintenance(conn: psycopg.Connection) -> dict[str, str]:
    applied: dict[str, str] = {}
    statements = {
        "maintenance_work_mem": "set maintenance_work_mem = '512MB'",
        "max_parallel_maintenance_workers": "set max_parallel_maintenance_workers = 4",
    }
    for name, statement in statements.items():
        try:
            conn.execute(statement)
        except psycopg.Error:
            continue
        applied[name] = dict(_MAINTENANCE)[name]
    return applied


def _pending_indexes(conn: psycopg.Connection) -> list[MigrationFile]:
    recorded = _recorded_checksums(conn)
    pending: list[MigrationFile] = []
    for item in list_migrations():
        if item.kind != "index":
            continue
        previous = recorded.get(item.filename)
        if previous is None:
            pending.append(item)
            continue
        if previous != item.checksum:
            raise RuntimeError(
                f"{item.filename} changed after it was applied; migrations are immutable"
            )
    return pending


def _recorded_checksums(conn: psycopg.Connection) -> dict[str, str]:
    exists = conn.execute(
        """
        select exists (
            select 1
            from information_schema.tables
            where table_schema = 'public' and table_name = 'schema_migration'
        )
        """
    ).fetchone()
    if not exists or not exists[0]:
        conn.execute(
            """
            create table if not exists schema_migration (
                filename text primary key,
                checksum text not null,
                applied_at timestamptz not null default now()
            )
            """
        )
        return {}
    rows = conn.execute("select filename, checksum from schema_migration").fetchall()
    return {filename: checksum for filename, checksum in rows}


def _measure(conn: psycopg.Connection) -> tuple[dict[str, int], dict[str, int]]:
    counts: dict[str, int] = {}
    for table in PIPELINE_TABLES:
        row = conn.execute(
            sql.SQL("select count(*) from {}").format(sql.Identifier(table))
        ).fetchone()
        counts[table] = int(row[0]) if row else 0
    patch_true, patch_false = _corpus_counts(conn, "patch")
    chunk_true, chunk_false = _corpus_counts(conn, "report_chunk")
    return counts, {
        "patch_true": patch_true,
        "patch_false": patch_false,
        "chunk_true": chunk_true,
        "chunk_false": chunk_false,
    }


def _corpus_counts(conn: psycopg.Connection, table: str) -> tuple[int, int]:
    row = conn.execute(
        sql.SQL(
            """
            select
                count(*) filter (where in_corpus),
                count(*) filter (where not in_corpus)
            from {}
            """
        ).format(sql.Identifier(table))
    ).fetchone()
    if row is None:
        return 0, 0
    return int(row[0]), int(row[1])


def _stage_and_upsert(
    conn: psycopg.Connection,
    table: str,
    columns: Sequence[str],
    rows: Sequence[tuple[object, ...]],
    *,
    casts: dict[str, str] | None = None,
) -> None:
    _stage(conn, table, columns, rows, vector_columns=tuple(casts or {}))
    _upsert_from_staging(conn, table, columns, casts=casts)


def _stage(
    conn: psycopg.Connection,
    table: str,
    columns: Sequence[str],
    rows: Sequence[tuple[object, ...]],
    *,
    vector_columns: Sequence[str] = (),
) -> None:
    staging = f"staging_{table}"
    definitions = sql.SQL(", ").join(
        sql.SQL("{} {}").format(
            sql.Identifier(column),
            sql.SQL("text" if column in vector_columns else _staging_type(column)),
        )
        for column in columns
    )
    conn.execute(
        sql.SQL("create temp table {} ({}) on commit drop").format(
            sql.Identifier(staging),
            definitions,
        )
    )
    if rows:
        _copy(conn, staging, columns, rows)


def _staging_type(column: str) -> str:
    if column in {
        "ordinal",
        "birth_year",
        "patient_age",
        "width",
        "height",
        "patch_size",
        "patch_count",
        "x",
        "y",
        "size",
        "thumb_length",
    }:
        return "integer"
    if column == "thumb_offset":
        return "bigint"
    if column in {"magnification", "mpp"}:
        return "double precision"
    flags = {
        "is_demo_user",
        "is_synthetic",
        "is_synthetic_linkage",
        "is_held_out",
        "in_corpus",
    }
    if column in flags:
        return "boolean"
    if column == "secondary_specialties":
        return "text[]"
    if column in {"created_at", "accessioned_at", "signed_at"}:
        return "timestamptz"
    return "text"


def _copy(
    conn: psycopg.Connection,
    staging: str,
    columns: Sequence[str],
    rows: Sequence[tuple[object, ...]],
) -> None:
    if not rows:
        return
    statement = sql.SQL("copy {} ({}) from stdin").format(
        sql.Identifier(staging),
        sql.SQL(", ").join(sql.Identifier(column) for column in columns),
    )
    with conn.cursor() as cursor:
        with cursor.copy(statement) as copy:
            for row in rows:
                copy.write_row(row)


def _upsert_from_staging(
    conn: psycopg.Connection,
    table: str,
    columns: Sequence[str],
    *,
    casts: dict[str, str] | None = None,
) -> None:
    casts = casts or {}
    column_list = sql.SQL(", ").join(sql.Identifier(column) for column in columns)
    select_list = sql.SQL(", ").join(_cast(column, casts.get(column)) for column in columns)
    assignments = sql.SQL(", ").join(
        sql.SQL("{} = excluded.{}").format(sql.Identifier(column), sql.Identifier(column))
        for column in columns
        if column != "id"
    )
    conn.execute(
        sql.SQL(
            """
            insert into {table} ({columns})
            select {select_list}
            from {staging}
            on conflict (id) do update set {assignments}
            """
        ).format(
            table=sql.Identifier(table),
            columns=column_list,
            select_list=select_list,
            staging=sql.Identifier(f"staging_{table}"),
            assignments=assignments,
        )
    )


def _insert_from_staging(
    conn: psycopg.Connection,
    table: str,
    columns: Sequence[str],
    *,
    casts: dict[str, str] | None = None,
) -> None:
    casts = casts or {}
    column_list = sql.SQL(", ").join(sql.Identifier(column) for column in columns)
    select_list = sql.SQL(", ").join(_cast(column, casts.get(column)) for column in columns)
    conn.execute(
        sql.SQL(
            """
            insert into {table} ({columns})
            select {select_list}
            from {staging}
            """
        ).format(
            table=sql.Identifier(table),
            columns=column_list,
            select_list=select_list,
            staging=sql.Identifier(f"staging_{table}"),
        )
    )


def _cast(column: str, cast: str | None) -> sql.Composable:
    if cast is None:
        return sql.Identifier(column)
    return sql.SQL("{}::{}").format(sql.Identifier(column), sql.SQL(cast))


def _read_rows(path: Path) -> list[dict[str, object]]:
    return pq.ParquetFile(path).read().to_pylist()


def _batched_rows(path: Path) -> Iterator[list[dict[str, object]]]:
    parquet = pq.ParquetFile(path)
    for batch in parquet.iter_batches(batch_size=BATCH_ROWS):
        rows = batch.to_pylist()
        if rows:
            yield rows


def _column_values(path: Path, column: str) -> list[str]:
    table = pq.read_table(path, columns=[column])
    return [str(value) for value in table.column(column).to_pylist() if value is not None]


def _parquet_rows(path: Path) -> int:
    metadata = pq.ParquetFile(path).metadata
    if metadata is None:
        return 0
    return int(metadata.num_rows)


def _text(value: object) -> str:
    if value is None:
        raise ValueError("a required text column is null")
    text = str(value).strip()
    if text == "":
        raise ValueError("a required text column is empty")
    return text


def _optional_text(value: object) -> str | None:
    if value is None:
        return None
    text = str(value).strip()
    if text == "":
        return None
    return text


def _optional_int(value: object) -> int | None:
    if value is None:
        return None
    return int(value)


def _required_int(value: object, label: str) -> int:
    if value is None:
        raise ValueError(f"{label} is null")
    return int(value)


def _text_list(value: object) -> list[str]:
    if value is None:
        return []
    return [str(item) for item in value]


def _timestamp(value: object) -> datetime:
    stamped = _optional_timestamp(value)
    if stamped is None:
        return datetime.now(UTC)
    return stamped


def _optional_timestamp(value: object) -> datetime | None:
    if value is None:
        return None
    if not isinstance(value, datetime):
        raise ValueError(f"expected a timestamp, got {type(value).__name__}")
    if value.tzinfo is None:
        return value.replace(tzinfo=UTC)
    return value


def _vector_text(value: object) -> str | None:
    if value is None:
        return None
    numbers = [float(item) for item in value]
    if not numbers:
        return None
    return "[" + ",".join(repr(number) for number in numbers) + "]"


def _project(elapsed: float, slides: int) -> float | None:
    if slides <= 0:
        return None
    return elapsed * (DEMO_SLIDES / slides)


def _seconds(value: float | None) -> str:
    if value is None:
        return "n/a"
    return f"{value:.3f}"
