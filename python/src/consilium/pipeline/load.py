@dataclass(frozen=True)
class LoadResult:
    """Row counts after a load, plus how long the copy and the indexes took."""

    counts: dict[str, int]
    patch_in_corpus_true: int
    patch_in_corpus_false: int
    report_chunk_in_corpus_true: int
    report_chunk_in_corpus_false: int
    slides_loaded: int
    load_elapsed_seconds: float
    index_elapsed_seconds: float
    projected_demo_load_seconds: float | None
    projected_demo_index_seconds: float | None
    indexes_applied: tuple[str, ...]
    maintenance_work_mem: str
    max_parallel_maintenance_workers: str

    def summary(self) -> str:
        lines = [f"{table} {self.counts[table]}" for table in PIPELINE_TABLES]
        lines.extend(
            [
                f"patch_in_corpus_true {self.patch_in_corpus_true}",
                f"patch_in_corpus_false {self.patch_in_corpus_false}",
                f"report_chunk_in_corpus_true {self.report_chunk_in_corpus_true}",
                f"report_chunk_in_corpus_false {self.report_chunk_in_corpus_false}",
                f"slides_loaded {self.slides_loaded}",
                f"load_elapsed_seconds {self.load_elapsed_seconds:.3f}",
                f"index_elapsed_seconds {self.index_elapsed_seconds:.3f}",
                f"projected_demo_slides {DEMO_SLIDES}",
                f"projected_demo_load_seconds {_seconds(self.projected_demo_load_seconds)}",
                f"projected_demo_index_seconds {_seconds(self.projected_demo_index_seconds)}",
                f"maintenance_work_mem {self.maintenance_work_mem}",
                f"max_parallel_maintenance_workers {self.max_parallel_maintenance_workers}",
                "indexes_applied "
                + (",".join(self.indexes_applied) if self.indexes_applied else "none"),
            ]
        )
        return "\n".join(lines) + "\n"


def load_parquet(
    export_dir: Path,
    *,
    database_url: str | None = None,
    replace_fixtures: bool = False,
) -> LoadResult:
    """Load the eight pipeline parquets, then build HNSW and GIN indexes."""
    directory = Path(export_dir)
    _require_files(directory)
    url = database_url if database_url is not None else resolve_database_url(None)
    _ensure_schema(url)
    slides_loaded = _parquet_rows(directory / PARQUET_FILES["slide"])
    started = time.perf_counter()
    conn = connect(url)
    try:
        with conn.transaction():
            if replace_fixtures:
                _replace_fixtures(conn, directory)
            _load_tables(conn, directory)
        load_elapsed = time.perf_counter() - started
        index_started = time.perf_counter()
        applied, maintenance = _ensure_indexes(conn)
        index_elapsed = time.perf_counter() - index_started
        counts, corpus = _measure(conn)
    finally:
        conn.close()
    return LoadResult(
        counts=counts,
        patch_in_corpus_true=corpus["patch_true"],
        patch_in_corpus_false=corpus["patch_false"],
        report_chunk_in_corpus_true=corpus["chunk_true"],
        report_chunk_in_corpus_false=corpus["chunk_false"],
        slides_loaded=slides_loaded,
        load_elapsed_seconds=load_elapsed,
        index_elapsed_seconds=index_elapsed,
        projected_demo_load_seconds=_project(load_elapsed, slides_loaded),
        projected_demo_index_seconds=_project(index_elapsed, slides_loaded),
        indexes_applied=tuple(applied),
        maintenance_work_mem=maintenance.get("maintenance_work_mem", "default"),
        max_parallel_maintenance_workers=maintenance.get(
            "max_parallel_maintenance_workers", "default"
        ),
    )


def _ensure_schema(url: str) -> None:
    """Apply ``0001_init.sql`` when it is pending. Leave indexes for later.

    A database that already has ``0002_indexes.sql`` is not an error: schema
    migration skips applied files and this call does not ask for indexes.
    Lakebase URLs are refused by ``migrate`` until SKO-280; the copy below
    still runs when that schema was applied some other way.
    """
    try:
        migrate(url, include_schema=True, include_indexes=False)
    except LakebaseMigrationRefused:
        return


def _require_files(directory: Path) -> None:
    if not directory.is_dir():
        raise ValueError(f"export directory not found: {directory}")
    missing = [
        name
        for name in LOAD_ORDER
        if not (directory / PARQUET_FILES[name]).is_file()
    ]
    if missing:
        names = ", ".join(PARQUET_FILES[name] for name in missing)
        raise ValueError(f"export directory is missing parquet files: {names}")


def _load_tables(conn: psycopg.Connection, directory: Path) -> None:
    _load_pathologists(conn, directory / PARQUET_FILES["pathologist"])
    _load_patients(conn, directory / PARQUET_FILES["patient"])
    _load_concepts(conn, directory / PARQUET_FILES["concept"])
    _load_cases(conn, directory / PARQUET_FILES["path_case"])
    _load_reports(conn, directory / PARQUET_FILES["report"])
    _load_chunks(conn, directory / PARQUET_FILES["report_chunk"])
    _load_slides_pending(conn, directory / PARQUET_FILES["slide"])
    _load_patches(conn, directory / PARQUET_FILES["patch"])
    _mark_slides_ready(conn)


